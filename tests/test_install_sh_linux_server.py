"""install.sh on a Linux server: the uninstaller removes a login service turned on after the
install (`abstractgateway service enable`, which the summary suggests), keeps one that runs
another gateway, and prints the linger command; the summary names the uninstall one-liner, the
default voice download and what a missing C compiler skips.

Simulated with stubs (uname -s = Linux, loginctl, systemctl) and `--print`, so nothing is run or
removed. Evidence: untracked/release-closing/ovh-test.log, step 5."""
from __future__ import annotations

import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
INSTALL_SH = ROOT / "scripts" / "install.sh"


def _linux_stubs(tmp_path: Path, *, linger: str = "no", compiler: bool = True) -> Path:
    fake = tmp_path / "fakebin"
    fake.mkdir(parents=True, exist_ok=True)
    stubs = {
        "uname": '#!/bin/sh\ncase "$1" in -s) echo Linux ;; -m) echo x86_64 ;; *) /usr/bin/uname "$@" ;; esac\n',
        "loginctl": f"#!/bin/sh\necho Linger={linger}\n",
        "systemctl": "#!/bin/sh\nexit 0\n",
    }
    if compiler:
        stubs["cc"] = "#!/bin/sh\nexit 0\n"
    for name, body in stubs.items():
        (fake / name).write_text(body)
        (fake / name).chmod(0o755)
    return fake


def _run(tmp_path: Path, fake: Path, *args: str, script: Path = INSTALL_SH) -> subprocess.CompletedProcess[str]:
    return subprocess.run(
        ["sh", str(script), *args],
        capture_output=True,
        text=True,
        env={"HOME": str(tmp_path), "PATH": f"{fake}:/usr/bin:/bin:/usr/sbin:/sbin", "TERM": "dumb"},
    )


def _background_install(tmp_path: Path, exec_start: str) -> Path:
    """State of an install whose start at login stayed off, then a unit written later."""
    data = tmp_path / ".local" / "share" / "abstractgateway"
    data.mkdir(parents=True)
    (data / "bootstrap.env").write_text("MODE=background\nPORT=8080\n")
    unit = tmp_path / ".config" / "systemd" / "user" / "abstractgateway.service"
    unit.parent.mkdir(parents=True)
    unit.write_text(
        "# Generated by `abstractgateway service install`. Remove with `abstractgateway service uninstall`.\n"
        f"[Service]\nExecStart={exec_start} serve\nRestart=on-failure\n\n[Install]\nWantedBy=default.target\n"
    )
    return unit


def test_uninstall_removes_a_service_enabled_after_a_background_install(tmp_path: Path) -> None:
    # What `abstractgateway service enable` writes for the uv tool's gateway (home as %h).
    unit = _background_install(tmp_path, "%h/.local/share/uv/tools/abstractgateway/bin/abstractgateway")
    proc = _run(tmp_path, _linux_stubs(tmp_path, linger="yes"), "--uninstall", "--print", "--yes")
    assert proc.returncode == 0, proc.stderr
    out = proc.stdout
    assert "no login service was registered by this install" not in out
    assert "a login service was turned on after the install (it starts this install's gateway): removing it" in out
    assert "$ systemctl --user disable --now abstractgateway.service" in out
    assert f"$ rm -f {unit}" in out
    assert "$ systemctl --user daemon-reload" in out
    # Lingering is never undone for you (sudo, and other services may need it): the command is printed.
    assert f"sudo loginctl disable-linger {__import__('getpass').getuser()}" in out


def test_uninstall_keeps_a_unit_of_another_gateway_and_prints_how_to_remove_it(tmp_path: Path) -> None:
    unit = _background_install(tmp_path, "/opt/other/bin/abstractgateway")
    proc = _run(tmp_path, _linux_stubs(tmp_path, linger="no"), "--uninstall", "--print", "--yes")
    assert proc.returncode == 0, proc.stderr
    out = proc.stdout
    assert "no login service was registered by this install (mode: background)" in out
    assert f"$ rm -f {unit}" not in out
    assert f"kept: {unit} starts a gateway this installer did not install" in out
    assert f"to remove it: systemctl --user disable --now abstractgateway.service; rm -f {unit}; systemctl --user daemon-reload" in out
    assert "disable-linger" not in out


def test_summary_names_the_uninstall_one_liner_and_the_default_voice_download(tmp_path: Path) -> None:
    proc = _run(tmp_path, _linux_stubs(tmp_path), "--print", "--profile", "light", "--port", "18999", "--no-tray")
    assert proc.returncode == 0, proc.stderr
    out = proc.stdout
    assert "Uninstall:  curl -LsSf https://abstractframework.ai/uninstall.sh | sh" in out
    assert "sh install.sh --uninstall" not in out
    assert "Uninstall AbstractFramework.command" not in out  # macOS only
    assert "its default voice downloads once: abstractgateway models download supertonic supertonic-3" in out


def test_no_compiler_says_what_is_skipped_and_the_apt_line(tmp_path: Path) -> None:
    # A real cc on the test machine cannot be hidden from PATH: the copy's probe finds none.
    sh = INSTALL_SH.read_text(encoding="utf-8")
    probe = "elif ! have cc && ! have gcc; then HAS_CC=0; fi"
    assert sh.count(probe) == 1
    script = tmp_path / "install.sh"
    script.write_text(sh.replace(probe, "else HAS_CC=0; fi"), encoding="utf-8")
    proc = _run(tmp_path, _linux_stubs(tmp_path, compiler=False), "--print", "--profile", "light", "--port", "18999",
                "--no-tray", script=script)
    assert proc.returncode == 0, proc.stderr
    out = proc.stdout
    assert "fine, all packages install as prebuilt wheels" not in out
    assert ("no C compiler: the terminal console and AbstractCode's terminal client (built with cargo) need one, so they "
            "are skipped unless already installed; to get them: sudo apt-get install -y build-essential (Debian/Ubuntu), "
            "then run the installer again") in out
    assert "not installed (building it needs a C compiler: sudo apt-get install -y build-essential (Debian/Ubuntu))" in out
    # --no-console: only what is still wanted is named.
    proc = _run(tmp_path, _linux_stubs(tmp_path, compiler=False), "--print", "--profile", "light", "--port", "18999",
                "--no-tray", "--no-console", script=script)
    assert proc.returncode == 0, proc.stderr
    assert ("no C compiler: AbstractCode's terminal client (built with cargo) needs one") in proc.stdout
    assert "no C compiler: the terminal console" not in proc.stdout


def test_uninstall_removes_only_its_own_entry_when_another_gateway_has_the_unit(tmp_path: Path) -> None:
    # This install's XDG autostart entry plus another gateway's systemd unit: the entry goes, the
    # unit stays (with the commands to remove it), whatever order the files are checked in.
    unit = _background_install(tmp_path, "/opt/other/bin/abstractgateway")
    entry = tmp_path / ".config" / "autostart" / "abstractgateway.desktop"
    entry.parent.mkdir(parents=True)
    entry.write_text(f"[Desktop Entry]\nType=Application\nExec={tmp_path}/.local/share/uv/tools/abstractgateway/bin/python -m abstractgateway.os_service launch\n")
    proc = _run(tmp_path, _linux_stubs(tmp_path), "--uninstall", "--print", "--yes")
    assert proc.returncode == 0, proc.stderr
    out = proc.stdout
    assert f"$ rm -f {entry}" in out
    assert f"$ rm -f {unit}" not in out
    assert "$ systemctl --user disable" not in out
    assert f"kept: {unit} starts a gateway this installer did not install" in out
